<?php
declare(strict_types=1);

require_once __DIR__ . '/../config/db.php';
require_once __DIR__ . '/../includes/auth.php';
require_once __DIR__ . '/../includes/layout.php';

$currentUser=require_role($pdo,['MANAGER']);

$summary=$pdo->query(
    "SELECT
       COUNT(*) total_rentals,
       SUM(status='ACTIVE') active_rentals,
       SUM(status='COMPLETED') completed_rentals,
       COALESCE(SUM(CASE WHEN status='COMPLETED' THEN amount ELSE 0 END),0) total_revenue
     FROM rentals"
)->fetch();

$perCar=$pdo->query(
    "SELECT c.reg_no,c.make,c.model,
            COUNT(r.id) rental_count,
            COALESCE(SUM(CASE WHEN r.status='COMPLETED' THEN r.amount ELSE 0 END),0) revenue
     FROM cars c
     LEFT JOIN rentals r ON r.car_id=c.id
     GROUP BY c.id,c.reg_no,c.make,c.model
     ORDER BY revenue DESC,c.reg_no"
)->fetchAll();

render_header('Revenue Statistics','reports.php');
?>
<section class="grid4">
<div class="card stat"><div class="label">Total Rentals</div><div class="value"><?=$summary['total_rentals']?></div></div>
<div class="card stat"><div class="label">Active Rentals</div><div class="value"><?=$summary['active_rentals']?></div></div>
<div class="card stat"><div class="label">Completed Rentals</div><div class="value"><?=$summary['completed_rentals']?></div></div>
<div class="card stat"><div class="label">Overall Revenue</div><div class="value money">SGD <?=number_format((float)$summary['total_revenue'],2)?></div></div>
</section>

<div class="panel top-gap">
<h3>Revenue Generated by Each Car</h3>
<p class="muted">Revenue is calculated from completed rental transactions.</p>
<div class="tablewrap">
<table>
<tr><th>Car</th><th>Rental Count</th><th>Revenue</th></tr>
<?php foreach($perCar as $r): ?>
<tr>
<td><b><?=h($r['reg_no'])?></b> — <?=h($r['make'].' '.$r['model'])?></td>
<td><?=$r['rental_count']?></td>
<td>SGD <?=number_format((float)$r['revenue'],2)?></td>
</tr>
<?php endforeach; ?>
</table>
</div>
</div>
<?php render_footer(); ?>
